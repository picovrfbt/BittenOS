"""Generate src/screen_font.h from the font and icon tables in data/screen_render.js.

The designer and the mask must draw identical pixels, so the firmware's tables are generated
from the designer's rather than typed out again.

    python tools/make_screen_font.py
"""
import io
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
JS = os.path.join(ROOT, 'data', 'screen_render.js')
OUT = os.path.join(ROOT, 'src', 'screen_font.h')

src = io.open(JS, encoding='utf-8').read()

font_match = re.search(r'const FONT = (\[\[.*?\]\]);', src, re.S)
if not font_match:
    raise SystemExit('FONT table not found in ' + JS)
font = json.loads(font_match.group(1))
if len(font) != 95:
    raise SystemExit('expected 95 characters (ASCII 32-126), got %d' % len(font))

icons_match = re.search(r'const ICONS = \{(.*?)\n  \};', src, re.S)
if not icons_match:
    raise SystemExit('ICONS table not found in ' + JS)
icons = re.findall(r'(\w+):\s*\[([^\]]+)\]', icons_match.group(1))
if not icons:
    raise SystemExit('no icons parsed')

widest = max(len(cols) for cols in font)

lines = [
    '//Generated by tools/make_screen_font.py from data/screen_render.js - do not edit by hand.',
    '//The 5x7 font (MD_MAX72XX system font, LGPL-2.1) and icons the screen designer draws with,',
    '//so the mask and the designer show the same pixels.',
    '#pragma once',
    '#include <Arduino.h>',
    '',
    '#define SCREEN_FONT_FIRST 32',
    '#define SCREEN_FONT_COUNT %d' % len(font),
    '#define SCREEN_FONT_MAXW %d' % widest,
    '',
    '//columns per character, bit 0 is the top row',
    'const uint8_t screenFontWidth[SCREEN_FONT_COUNT] PROGMEM = {',
]
lines.append('  ' + ', '.join(str(len(cols)) for cols in font) + '};')
lines.append('')
lines.append('const uint8_t screenFont[SCREEN_FONT_COUNT][SCREEN_FONT_MAXW] PROGMEM = {')
for cols in font:
    padded = list(cols) + [0] * (widest - len(cols))
    lines.append('  {' + ','.join('0x%02X' % c for c in padded) + '},')
lines.append('};')
lines.append('')
lines.append('//8x8 icons, top row first, bit 7 leftmost')
lines.append('#define SCREEN_ICON_COUNT %d' % len(icons))
lines.append('const char *const screenIconNames[SCREEN_ICON_COUNT] = {')
lines.append('  ' + ', '.join('"%s"' % name for name, _ in icons) + '};')
lines.append('')
lines.append('const uint8_t screenIcons[SCREEN_ICON_COUNT][8] PROGMEM = {')
for name, body in icons:
    values = [int(v.strip(), 0) for v in body.split(',') if v.strip()]
    if len(values) != 8:
        raise SystemExit('icon %s has %d rows, expected 8' % (name, len(values)))
    lines.append('  {' + ','.join('0x%02X' % v for v in values) + '}, //' + name)
lines.append('};')
lines.append('')

io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote %s: %d characters, %d icons' % (OUT, len(font), len(icons)))
